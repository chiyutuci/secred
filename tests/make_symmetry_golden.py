#!/usr/bin/env python3
"""Regenerate tests/symmetry_golden.h from the archived Kira goldens.

Usage: python3 -I tests/make_symmetry_golden.py bench/symmetry/native tests/symmetry_golden.h

The goldens are third-party program output kept for comparison only; they are
read here, never executed.
"""
import pathlib
import sys

FAMILIES = [("box", "BOX"), ("sunrise", "SUNRISE"), ("dbox", "DBOX")]
KINDS = [("canonica", "CANONICA"), ("relations", "RELATIONS"), ("symmetries", "SYMMETRIES")]


def main() -> int:
    src = pathlib.Path(sys.argv[1])
    dst = pathlib.Path(sys.argv[2])
    out = [
        "// Generated by tests/make_symmetry_golden.py -- do not edit by hand.",
        "// The Kira 3.0 sector-mapping goldens for box, sunrise and dbox, verbatim.",
        "#pragma once",
        "",
    ]
    for fam, up in FAMILIES:
        for kind, upk in KINDS:
            p = src / f"{fam}_sym" / "sectormappings" / fam / kind
            text = p.read_text()
            if ')RAW"' in text:
                raise SystemExit(f"{p}: contains the raw-string terminator")
            out.append(f'static const char *GOLDEN_{up}_{upk} = R"RAW({text})RAW";')
            out.append("")
    out += [
        "inline const char *golden_canonica(const char *fam) {",
        '  if (fam[0] == \'b\') return GOLDEN_BOX_CANONICA;',
        '  if (fam[0] == \'s\') return GOLDEN_SUNRISE_CANONICA;',
        "  return GOLDEN_DBOX_CANONICA;",
        "}",
        "",
        "inline const char *golden_entries(const char *fam, bool selfs) {",
        '  if (fam[0] == \'b\') return selfs ? GOLDEN_BOX_SYMMETRIES : GOLDEN_BOX_RELATIONS;',
        '  if (fam[0] == \'s\') return selfs ? GOLDEN_SUNRISE_SYMMETRIES : GOLDEN_SUNRISE_RELATIONS;',
        "  return selfs ? GOLDEN_DBOX_SYMMETRIES : GOLDEN_DBOX_RELATIONS;",
        "}",
        "",
    ]
    dst.write_text("\n".join(out))
    print(f"{dst}: {dst.stat().st_size} bytes, {len(FAMILIES) * len(KINDS)} tables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
